"""Lay the synthesized lines on a timeline and plan the music.

usage: python build_timeline.py <workdir> [align.json]
reads   tools/script.txt, <workdir>/voice/<key>.wav, optional per-line char times from align.py
writes  assets/timeline.js (window.TL), <workdir>/voice_track.wav, <workdir>/plan.json
"""
import sys, os, json
import numpy as np, soundfile as sf
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from script_parse import parse

root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
work = sys.argv[1]
align = json.load(open(sys.argv[2])) if len(sys.argv) > 2 and os.path.exists(sys.argv[2]) else {}
SR = 48000
LEAD = 0.9          # silence before the first line (title card)
SEC_LEAD = 0.45     # a section's visuals start this long before its first line

from voice_util import load
import re, jieba
jieba.setLogLevel(60)

def sub_break(sub, max_len=15):
    """where to break a long subtitle into two rows (same rule as splitSub in src/timeline.js: the punctuation
    mark closest to the middle), but when there is none, break between words (jieba) instead of mid-word"""
    s = re.sub(r'[，。：；]$', '', sub)
    if len(s) <= max_len: return None
    cands = [i + 1 for i in range(4, len(s) - 3) if s[i] in '，、：；。！？ ']
    best = min(cands, key=lambda a: abs(a - (len(s) - a)), default=-1)
    if best < 0 or max(best, len(s) - best) > max_len + 4:
        ws = list(jieba.cut(s)); pos, cost = 0, {}
        for k, w in enumerate(ws[:-1]):
            pos += len(w); nxt = ws[k + 1]
            cost[pos] = (abs(pos - len(s) / 2)
                         + (4 if nxt[0] in '的了地得着过们' else 0)          # never start a row with a particle
                         + (3 if w in ('和', '与', '把', '对', '在', '给', '被', '是', '说', '那', '这') else 0)  # nor end on a preposition
                         - (1 if w.endswith('的') or w == '时候' else 0))  # a row ending on 的 reads naturally
        best = min(cost, key=cost.get)
    return best

WEIGHT_PAUSE = '，、：；'
def char_times(text, t0, dur):
    """Proportional estimate: CJK ≈ 1, latin letter ≈ 0.4, inner comma adds a pause."""
    w = []
    for ch in text:
        if ch in WEIGHT_PAUSE: w.append(0.9)
        elif ch in '。！？!?（）「」《》…':  w.append(0.0)
        elif ch.isascii(): w.append(0.4 if ch.isalnum() else 0.1)
        else: w.append(1.0)
    tot = sum(w) or 1
    out, acc = [], 0.0
    for x in w:
        out.append(round(t0 + dur * acc / tot, 3)); acc += x
    return out

secs = parse(os.path.join(root, 'tools', 'script.txt'))
t = LEAD
clips = []
for si, s in enumerate(secs):
    s['t0'] = 0.0 if si == 0 else round(t - SEC_LEAD, 3)
    for l in s['lines']:
        wav = f"{work}/voice/{l['key']}.wav"
        if os.path.exists(wav): y = load(wav)
        else:  # draft mode: placeholder silence sized from the text (≈5.3 chars/s) until the line is synthesized
            print('  (placeholder)', l['sub'][:20]); y = np.zeros(int(len(l['say']) / 5.3 * SR), np.float32)
        d = len(y) / SR
        l['t0'], l['t1'] = round(t, 3), round(t + d, 3)
        a = align.get(l['key'])
        l['ch'] = [round(t + x, 3) for x in a] if a and len(a) == len(l['sub']) else char_times(l['sub'], t, d)
        clips.append((t, y))
        t += d + l['pause']
dur = round(t + 0.6, 3)
for si, s in enumerate(secs):
    s['t1'] = secs[si + 1]['t0'] if si + 1 < len(secs) else dur

# voice track
vt = np.zeros(int(dur * SR) + SR, dtype=np.float32)
for t0, y in clips:
    i = int(t0 * SR); vt[i:i + len(y)] += y
sf.write(f'{work}/voice_track.wav', vt, SR)

# ── music plan: [track, tl_start, tl_end, src_start, gain_dB, fade_in, fade_out]
S = {s['id']: s for s in secs}
plan = [
    ['lofi_p7', 0.0, S['anon']['t0'] + 1.0, 0.0, -20, 1.2, 1.5],
    ['lofi_p9', S['anon']['t0'] - 0.2, S['soyo']['t0'] + 1.0, 4.0, -20, 1.0, 1.4],
    # the two piano covers are mastered ~22 dB quieter than the Lo-Fi tracks (median −31.5 vs −9 dBFS), hence the higher gain
    ['haruhikage', S['soyo']['t0'] - 0.2, S['uika']['t0'] + 1.2, 0.0, -2, 1.2, 1.8],
    ['imprisoned', S['uika']['t0'] - 0.3, dur, 0.0, -2, 2.0, 3.0],
]
if plan[-1][2] - plan[-1][1] > 181: plan[-1][3] = 0.0   # longer than the track: it simply ends early (fade covers it)
boost = []
json.dump({'dur': dur, 'plan': plan, 'boost': boost}, open(f'{work}/plan.json', 'w'), indent=1)
tl = {'dur': dur, 'music': [{'track': p[0], 't0': round(p[1], 3), 't1': round(p[2], 3), 'src': round(p[3], 3)} for p in plan],
      'sections': [{'id': s['id'], 'title': s['title'], 't0': s['t0'], 't1': s['t1'],
                    'lines': [{'sub': l['sub'], 't0': l['t0'], 't1': l['t1'], 'ch': l['ch'], 'br': sub_break(l['sub'])} for l in s['lines']]} for s in secs]}
with open(os.path.join(root, 'assets', 'timeline.js'), 'w', encoding='utf-8') as f:
    f.write('// Generated by tools/build_timeline.py\nwindow.TL = ' + json.dumps(tl, ensure_ascii=False, separators=(',', ':')) + ';\n')
print(f'duration {dur:.1f}s')
for s in secs: print(f"  {s['t0']:7.2f}  {s['id']}")
