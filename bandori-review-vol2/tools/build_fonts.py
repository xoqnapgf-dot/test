"""Subset the fonts to the glyphs actually used and emit assets/fonts.js (base64 WOFF2).
usage: python build_fonts.py <dir-with-ttf>"""
import sys, os, glob, io, base64
from fontTools import subset
from fontTools.ttLib import TTFont
from fontTools.varLib import instancer

root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
src = sys.argv[1]
chars = set(chr(c) for c in range(0x20, 0x7f))
for f in glob.glob(os.path.join(root, 'src', '*.js')) + [os.path.join(root, 'tools', 'script.txt'), os.path.join(root, 'index.html')]:
    chars |= set(open(f, encoding='utf8').read())
chars |= set('0123456789%×+-…。，、：；！？（）「」《》')
text = ''.join(sorted(c for c in chars if c.isprintable()))
FONTS = {  # family: (file, wght or None)
    'NSC9': ('NotoSansSC[wght].ttf', 900), 'NSC7': ('NotoSansSC[wght].ttf', 700), 'NSC5': ('NotoSansSC[wght].ttf', 500),
    'SER': ('NotoSerifSC[wght].ttf', 700), 'KL': ('ZCOOLKuaiLe-Regular.ttf', None), 'HY': ('ZCOOLQingKeHuangYou-Regular.ttf', None),
    'WK': ('LXGWWenKai-Regular.ttf', None), 'FR': ('Fredoka[wdth,wght].ttf', 600),
}
out = ['// Generated by tools/build_fonts.py — subset WOFF2 fonts (SIL OFL 1.1, see assets/LICENSES.md)', 'window.BR_FONTS = {']
total = 0
for fam, (fn, w) in FONTS.items():
    font = TTFont(os.path.join(src, fn))
    if w is not None:
        axes = {'wght': w}
        if 'wdth' in [a.axisTag for a in font['fvar'].axes]: axes['wdth'] = 100
        font = instancer.instantiateVariableFont(font, axes)
    cmap = font.getBestCmap()
    missing = [c for c in text if ord(c) not in cmap and not c.isspace()]
    opts = subset.Options(); opts.flavor = 'woff2'; opts.layout_features = ['*']; opts.notdef_outline = True
    sub = subset.Subsetter(opts); sub.populate(text=text); sub.subset(font)
    buf = io.BytesIO(); font.flavor = 'woff2'; font.save(buf); b = buf.getvalue(); total += len(b)
    out.append(f'  "{fam}": "{base64.b64encode(b).decode()}",')
    print(fam, len(b), 'missing:', ''.join(missing[:60]) if fam in ('NSC9', 'NSC7', 'WK', 'HY', 'FR') else len(missing))
out.append('};')
open(os.path.join(root, 'assets', 'fonts.js'), 'w').write('\n'.join(out) + '\n')
print('glyphs', len(text), 'bytes', total)
