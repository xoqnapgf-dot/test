"""Subset Noto Sans SC / Noto Serif SC to the characters the page uses -> assets/fonts.css

    cd tools && npm install            # fetches @fontsource/noto-sans-sc, noto-serif-sc
    python3 make_fonts.py

The fontsource packages ship each weight as ~100 unicode-range slices. For every slice
that holds a character we need, the slice is subset to just those characters and written
as an @font-face with a data: URI and a unicode-range limited to those characters, so the
page works from file:// with no font requests. Characters are collected from every source
file of the page, so new UI text is picked up automatically when this is re-run.
Fonts: SIL Open Font License 1.1 (see assets/LICENSES.md).
"""
import base64
import io
import os
import re

from fontTools import subset
from fontTools.ttLib import TTFont

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
NM = os.path.join(HERE, "node_modules", "@fontsource")

FACES = [
    # (package, css family, weight)
    ("noto-sans-sc", "MV Sans", 400),
    ("noto-sans-sc", "MV Sans", 500),
    ("noto-sans-sc", "MV Sans", 700),
    ("noto-serif-sc", "MV Serif", 600),
]


def needed_chars():
    text = ""
    for rel in ["index.html", "src/data.js", "src/app.js", "src/overlay.js", "src/timeline.js"]:
        p = os.path.join(ROOT, rel)
        if os.path.exists(p):
            s = open(p, encoding="utf-8").read()
            if rel.endswith("data.js"):
                s = re.sub(r'"(spec|low|loud)":"[^"]*"', "", s)
            text += s
    chars = {c for c in text if ord(c) > 0x7F}
    chars |= {chr(c) for c in range(0x20, 0x7F)}
    chars |= set("·—…“”‘’，。、？！：；（）《》「」　")
    return chars


def parse_css(path):
    css = open(path, encoding="utf-8").read()
    faces = []
    for block in re.findall(r"@font-face\s*{(.*?)}", css, re.S):
        src = re.search(r"url\(\./files/([^)]+\.woff2)\)", block).group(1)
        rng = re.search(r"unicode-range:\s*([^;]+);", block).group(1)
        cps = set()
        for part in rng.split(","):
            part = part.strip()[2:]
            if "-" in part:
                a, b = part.split("-")
                cps.update(range(int(a, 16), int(b, 16) + 1))
            else:
                cps.add(int(part, 16))
        faces.append((src, cps))
    return faces


def urange(cps):
    cps = sorted(cps)
    out, i = [], 0
    while i < len(cps):
        j = i
        while j + 1 < len(cps) and cps[j + 1] == cps[j] + 1:
            j += 1
        out.append("U+%x" % cps[i] if i == j else "U+%x-%x" % (cps[i], cps[j]))
        i = j + 1
    return ",".join(out)


def main():
    chars = needed_chars()
    cps_needed = {ord(c) for c in chars}
    css_out = ["/* Generated by tools/make_fonts.py. Noto Sans SC / Noto Serif SC, SIL OFL 1.1. */"]
    total = 0
    missing_all = None
    for pkg, family, weight in FACES:
        base = os.path.join(NM, pkg)
        covered = set()
        for src, cps in parse_css(os.path.join(base, "%d.css" % weight)):
            want = cps & cps_needed
            if not want:
                continue
            font = TTFont(os.path.join(base, "files", src))
            have = set(font.getBestCmap().keys())
            want &= have
            if not want:
                continue
            opts = subset.Options()
            opts.flavor = "woff2"
            opts.layout_features = ["*"]
            opts.name_IDs = ["*"]
            opts.notdef_outline = True
            sub = subset.Subsetter(opts)
            sub.populate(unicodes=sorted(want))
            sub.subset(font)
            buf = io.BytesIO()
            font.flavor = "woff2"
            font.save(buf)
            data = buf.getvalue()
            total += len(data)
            covered |= want
            css_out.append(
                "@font-face{font-family:'%s';font-style:normal;font-weight:%d;font-display:block;"
                "src:url(data:font/woff2;base64,%s) format('woff2');unicode-range:%s;}"
                % (family, weight, base64.b64encode(data).decode(), urange(want))
            )
        miss = cps_needed - covered
        missing_all = miss if missing_all is None else (missing_all & miss)
        print("%-14s %d: %d chars, missing %s" % (pkg, weight, len(covered),
              "".join(sorted(chr(c) for c in miss if c > 0x7F))[:40]))
    out = os.path.join(ROOT, "assets", "fonts.css")
    open(out, "w").write("\n".join(css_out) + "\n")
    print("wrote", out, os.path.getsize(out), "bytes (%d bytes of woff2)" % total)


if __name__ == "__main__":
    main()
