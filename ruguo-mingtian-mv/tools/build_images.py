"""Pack the image layers into src/images.js as data URIs.

    python3 tools/build_images.py

WebGL refuses to upload images loaded from file:// (each file is its own origin to Chrome),
but data: URIs are fine, so the textures travel inside a classic script.

  cover  assets/cover.jpg                      the artwork as delivered
  plate  assets/plate.jpg                      the artwork with the walker removed
  walker assets/walker.jpg                     walker colours, bled past his outline
  aux    R = plate depth, G = artwork depth (reference, unused by the shader), B = walker alpha
"""
import base64
import io
import json
import os

import numpy as np
from PIL import Image

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)


def uri(path, mime):
    return "data:%s;base64,%s" % (mime, base64.b64encode(open(path, "rb").read()).decode())


def main():
    A = lambda n: os.path.join(ROOT, "assets", n)
    pd = np.asarray(Image.open(A("plate-depth.png")).convert("L"))
    cd = np.asarray(Image.open(A("cover-depth.png")).convert("L"))
    m = np.asarray(Image.open(A("walker-mask.png")).convert("L"))
    aux = Image.fromarray(np.stack([pd, cd, m], -1), "RGB")
    buf = io.BytesIO()
    aux.save(buf, "PNG", optimize=True)
    aux_uri = "data:image/png;base64," + base64.b64encode(buf.getvalue()).decode()
    info = json.load(open(os.path.join(HERE, "layers.json")))
    out = os.path.join(ROOT, "src", "images.js")
    with open(out, "w") as f:
        f.write("// Generated by tools/build_images.py. Do not edit by hand.\n")
        f.write("window.MV_IMAGES = ")
        json.dump({
            "cover": uri(A("cover.jpg"), "image/jpeg"),
            "plate": uri(A("plate.jpg"), "image/jpeg"),
            "walker": uri(A("walker.jpg"), "image/jpeg"),
            "aux": aux_uri,
            "walkerInfo": info,
        }, f)
        f.write(";\n")
    print("wrote", out, os.path.getsize(out), "bytes")


if __name__ == "__main__":
    main()
