"""Concatenate src/*.js (in dependency order) into one classic script: app.js."""
import os
root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
ORDER = ['engine', 'widgets', 'timeline', 'scenes_ppp', 'scenes_duo', 'scenes_rp', 'sfx', 'main']
parts = ['// Generated by tools/bundle.py from src/ — edit the sources, then rebuild.\n(() => {\n"use strict";']
for n in ORDER:
    parts.append(f'\n// ===== src/{n}.js =====\n' + open(os.path.join(root, 'src', n + '.js'), encoding='utf8').read())
parts.append('\n})();\n')
open(os.path.join(root, 'app.js'), 'w', encoding='utf8').write(''.join(parts))
print('app.js', os.path.getsize(os.path.join(root, 'app.js')), 'bytes')
