"""Mix narration + music (with ducking) + synthesized sound effects; write the visualizer data.

usage: python build_audio.py <workdir> <music_dir> [sfx.json]
  music_dir holds lofi_p1/p2/p5/p10.wav, maesusume.wav, ars_piano.wav (48 kHz, see README)
  sfx.json  is the cue list exported from the page (tools/render.mjs --cues); optional
writes assets/viz.js always; assets/audio.mp3 when sfx.json is given (or with --no-sfx)
"""
import sys, os, json, subprocess
import numpy as np, soundfile as sf

root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
work, mdir = sys.argv[1], sys.argv[2]
cues_path = next((a for a in sys.argv[3:] if a.endswith('.json')), None)
SR = 48000
plan = json.load(open(f'{work}/plan.json'))
dur = plan['dur']; N = int(dur * SR)
db = lambda x: 10 ** (x / 20)

def stereo(path):
    y, sr = sf.read(path, dtype='float32')
    assert sr == SR, path
    return y if y.ndim == 2 else np.stack([y, y], 1)

# ── music bus
music = np.zeros((N, 2), np.float32)
tracks = {}
for name, t0, t1, src, gain, fin, fout in plan['plan']:
    if name not in tracks: tracks[name] = stereo(f'{mdir}/{name}.wav')
    y = tracks[name]
    i0, i1 = int(t0 * SR), min(N, int(t1 * SR)); n = i1 - i0
    s0 = int(src * SR)
    seg = y[s0:s0 + n]
    if len(seg) < n: seg = np.concatenate([seg, np.zeros((n - len(seg), 2), np.float32)])
    env = np.ones(n, np.float32)
    a, b = int(fin * SR), int(fout * SR)
    if a: env[:a] = np.linspace(0, 1, a) ** 1.5
    if b: env[-b:] *= np.linspace(1, 0, b) ** 1.5
    music[i0:i1] += seg * (env * db(gain))[:, None]
for t0, t1, g in plan.get('boost', []):
    i0, i1 = int(t0 * SR), int(t1 * SR); n = i1 - i0; r = int(0.8 * SR)
    env = np.ones(n, np.float32) * db(g)
    env[:r] = np.linspace(1, db(g), r); env[-r:] = np.linspace(db(g), 1, r)
    music[i0:i1] *= env[:, None]

# ── visualizer data from the (pre-duck) music bus: 30 fps, level + 8 log bands
FPS = 30; hop = SR // FPS; mono = music.mean(1)
nfr = int(dur * FPS); win = np.hanning(2048)
edges = np.geomspace(60, 12000, 9); freqs = np.fft.rfftfreq(2048, 1 / SR)
frames = []
for f in range(nfr):
    i = f * hop; x = mono[i:i + 2048]
    if len(x) < 2048: x = np.pad(x, (0, 2048 - len(x)))
    spec = np.abs(np.fft.rfft(x * win))
    lvl = np.sqrt((x ** 2).mean())
    bands = [spec[(freqs >= edges[b]) & (freqs < edges[b + 1])].mean() for b in range(8)]
    frames.append([lvl] + bands)
fr = np.array(frames)
fr[:, 0] = np.clip(fr[:, 0] / (np.percentile(fr[:, 0], 98) + 1e-9), 0, 1)
for b in range(1, 9): fr[:, b] = np.clip(np.log1p(fr[:, b]) / (np.percentile(np.log1p(fr[:, b]), 98) + 1e-9), 0, 1)
fr = (fr * 255).astype(int)
song = tracks.get('maesusume')
if song is None: song = stereo(f'{mdir}/maesusume.wav')
sm = song.mean(1); seg = len(sm) // 160
senv = np.array([np.sqrt((sm[i * seg:(i + 1) * seg] ** 2).mean()) for i in range(160)])
senv = (np.clip((senv - senv.min()) / (senv.max() - senv.min() + 1e-9), 0, 1) ** 1.6 * 255).astype(int)
with open(os.path.join(root, 'assets', 'viz.js'), 'w') as f:
    f.write('// Generated by tools/build_audio.py — music levels for the visualizer\n')
    f.write('window.VIZ = ' + json.dumps({'fps': FPS, 'songDur': round(len(sm) / SR, 2), 'song': senv.tolist(), 'frames': fr.tolist()}, separators=(',', ':')) + ';\n')
print('viz frames', len(fr))
if not cues_path and '--no-sfx' not in sys.argv: sys.exit(0)

# ── ducking under the narration
voice, _ = sf.read(f'{work}/voice_track.wav', dtype='float32')
voice = np.pad(voice, (0, max(0, N - len(voice))))[:N]
blk = SR // 100
act = np.array([np.abs(voice[i:i + blk]).max() for i in range(0, N, blk)]) > 0.02
g = np.zeros(len(act)); cur = 0.0
for i, a in enumerate(act):            # attack 60 ms, release 450 ms (in 10 ms blocks)
    cur = min(1, cur + 1 / 6) if a else max(0, cur - 1 / 45); g[i] = cur
duck = np.repeat(db(-7) ** g, blk)[:N].astype(np.float32)
music *= duck[:, None]

# ── sound effects
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from sfx import SOUNDS
fx = np.zeros(N, np.float32)
for t, name, gain in (json.load(open(cues_path)) if cues_path else []):
    s = SOUNDS[name](SR) * gain * db(-15)
    i = int(t * SR); j = min(N, i + len(s)); fx[i:j] += s[:j - i]

mix = music + np.stack([voice, voice], 1) * db(-1) + np.stack([fx, fx], 1)
peak = np.abs(mix).max()
if peak > 0.98: mix *= 0.98 / peak
sf.write(f'{work}/mix.wav', mix, SR)
out = os.path.join(root, 'assets', 'audio.mp3')
subprocess.run(['ffmpeg', '-loglevel', 'error', '-y', '-i', f'{work}/mix.wav', '-af', 'loudnorm=I=-15:TP=-1.5:LRA=11',
                '-ar', '44100', '-c:a', 'libmp3lame', '-b:a', '192k', out], check=True)
print('wrote', out, os.path.getsize(out) // 1024, 'KB')
